alter table public.problem_progress
add column if not exists revision_enabled boolean default false;

alter table public.problem_progress
add column if not exists next_revision_date date;

create table if not exists public.problem_revisions (
  id bigint generated by default as identity primary key,
  problem_id bigint not null references public.problems(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  revision_number integer not null default 1,
  scheduled_date date not null,
  completed_at timestamptz,
  status text not null default 'pending' check (status in ('pending','completed')),
  created_at timestamptz default now()
);

create index if not exists problem_revisions_user_date_idx
on public.problem_revisions(user_id, scheduled_date);

create index if not exists problems_user_pattern_idx
on public.problems(user_id, pattern);

create index if not exists problems_user_topic_idx
on public.problems(user_id, topic);

alter table public.problem_revisions enable row level security;

drop policy if exists "Users can view own revisions" on public.problem_revisions;
drop policy if exists "Users can create own revisions" on public.problem_revisions;
drop policy if exists "Users can update own revisions" on public.problem_revisions;
drop policy if exists "Users can delete own revisions" on public.problem_revisions;

create policy "Users can view own revisions"
on public.problem_revisions for select
using (auth.uid() = user_id);

create policy "Users can create own revisions"
on public.problem_revisions for insert
with check (auth.uid() = user_id);

create policy "Users can update own revisions"
on public.problem_revisions for update
using (auth.uid() = user_id);

create policy "Users can delete own revisions"
on public.problem_revisions for delete
using (auth.uid() = user_id);

-- Backfill existing solved problems that do not yet have a revision schedule.
insert into public.problem_revisions (problem_id, user_id, revision_number, scheduled_date, status)
select pp.problem_id, pp.user_id, 1, pp.completed_date + 3, 'pending'
from public.problem_progress pp
where not exists (
  select 1 from public.problem_revisions pr
  where pr.problem_id = pp.problem_id
    and pr.user_id = pp.user_id
);
